import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";

const output = new URL("../apps/site/public/installers/connect-codex-v1.mjs", import.meta.url);
const result = await build({
  entryPoints: [new URL("./codex-connect/entry.mjs", import.meta.url).pathname],
  bundle: true, platform: "node", format: "esm", target: "node22", write: false,
  banner: { js: "/* eslint-disable */\n// Generated by scripts/build-codex-installer.mjs. Do not edit directly." },
});
const bundled = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== bundled) throw new Error("Codex installer is stale. Run pnpm build:codex-installer.");
} else await writeFile(output, bundled);
