import test from "node:test";
import assert from "node:assert/strict";
import { createMeshCache } from "../../../../dist/features/rendering/services/meshCache.service.js";
void test("mesh cache evicts least recently used entries by count and bytes", () => {
  const mesh = (size) => ({ bytes: new Uint8Array(size), diagnostics: [] });
  const cache = createMeshCache(2, 6);
  cache.set("a", mesh(2));
  cache.set("b", mesh(2));
  assert.ok(cache.get("a"));
  cache.set("c", mesh(2));
  assert.equal(cache.get("b"), undefined);
  cache.set("d", mesh(5));
  assert.equal(cache.get("a"), undefined);
  assert.equal(cache.get("c"), undefined);
  assert.equal(cache.get("d").bytes.length, 5);
  cache.set("d", mesh(7));
  assert.equal(cache.get("d"), undefined);
  cache.set("e", mesh(6));
  assert.equal(cache.get("e").bytes.length, 6);
});
